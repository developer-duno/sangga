/**
 * 종이로 뽑기 — 브라우저의 **기본 인쇄**를 부른다.
 *
 * 왜 버튼이 따로 필요한가
 * -----------------------
 * 컴퓨터에는 Ctrl+P 가 있지만 **휴대폰에는 없다**(브라우저 메뉴를 뒤져야 하고, 그 자리가
 * 기기마다 다르다). 이 앱은 현장에서 좁은 화면으로 보는 일이 많아(모바일 E2E 를 따로 도는
 * 이유가 그것이다) 버튼 하나가 실제 문턱을 크게 낮춘다 — `ShareButton` 과 같은 판단이다.
 *
 * ⛔ 이 버튼은 **편의일 뿐, 인쇄의 유일한 길이 아니다**
 * -----------------------------------------------------
 * 사용자는 언제든 Ctrl+P·브라우저 메뉴·공유 시트로 인쇄할 수 있다. 그래서 "이 버튼을
 * 눌렀을 때만 종이가 제대로 나오는" 구조를 만들면 안 된다 — 그런 구조는 다른 길로 들어온
 * 사람에게 **말없이 반쪽짜리 종이**를 준다.
 *
 * 그래서 접힌 카드를 펴는 일은 이 버튼이 아니라 **인쇄 CSS** 가 한다. `SectionCard` 가
 * 접힌 본문도 그려 두는(감추기만 하는) 이유가 정확히 이것이다 — 어느 길로 인쇄하든 같은
 * 종이가 나온다.
 *
 * ⓘ 왜 인쇄 라이브러리를 안 쓰나 — `styles.css` 의 『종이로 뽑기』 블록 머리말 참조
 *   (사진으로 찍는 방식은 지도 타일을 못 잡고 글자가 그림이 된다).
 */
export function PrintButton() {
  return (
    <button type="button" className="print__btn" onClick={() => window.print()}>
      인쇄 · PDF로 저장
    </button>
  );
}
