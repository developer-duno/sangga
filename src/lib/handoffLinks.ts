export type HandoffLink = {
  /** 화면에 적히는 이름. 그 서비스가 스스로 부르는 이름을 쓴다. */
  readonly label: string;
  /** 첫 화면 주소만 적는다 — 깊은 주소는 그쪽이 개편하면 조용히 죽는다. */
  readonly href: string;
};

export type HandoffGroup = {
  readonly id: string;
  /** 무엇이 필요할 때 여기로 가나. */
  readonly need: string;
  /** 거기서 무엇을 볼 수 있나 — 한 문장. */
  readonly what: string;
  readonly links: readonly HandoffLink[];
};

