/**
 * 종이에 적을 "언제 뽑았나" 한 줄을 만드는 **순수 부품**.
 *
 * 왜 따로 떼어 두나
 * -----------------
 * 시각 만들기를 컴포넌트 안에 두면 시험이 브라우저를 흉내 내야 확인할 수 있다. 값(Date)만
 * 넣어 형식을 볼 수 있게 떼어 둔다 — `urlState.ts`·`appConstants.ts` 가 순수 모듈인 것과
 * 같은 이유다.
 *
 * 왜 `toLocaleString` 이 아닌가
 * -----------------------------
 * 같은 날짜라도 브라우저·운영체제의 지역 설정에 따라 `2026. 8. 25. 오전 3:20` 처럼 모양이
 * 달라진다. 종이에 박히는 글자라 **어디서 뽑든 같은 모양**이어야 하고, 시험도 모양을 고정할
 * 수 있어야 한다. 그래서 손으로 맞춘다.
 *
 * ⚠️ **시간대는 보는 사람의 것을 쓴다.** 이 값은 자료의 기준 시점이 아니라 "이 종이를 뽑은
 *    시각"이라, 뽑은 사람이 있는 곳의 시계로 적히는 것이 맞다. (자료의 기준 시점은 각
 *    섹션이 자기 출처 줄에 따로 적는다 — 그건 서버가 준 값이라 우리가 만들지 않는다.)
 * ⚠️ **시험에 시각을 박아 넣지 말 것.** 돌리는 날·시간대에 따라 값이 달라져 언젠가 남의
 *    PR 을 막으며 터진다. 넣은 Date 로 나온 값을 견주거나, 형식만 본다.
 */

/** 두 자리로 맞춘다(3 → "03"). 종이에서 자릿수가 흔들리면 눈이 흔들린다. */
function pad2(n: number): string {
  return String(n).padStart(2, '0');
}

/**
 * `2026-08-25 03:20` 형태로 만든다.
 *
 * @param at 뽑는 시각. 부르는 쪽이 `new Date()` 를 넘긴다(이 함수는 시계를 안 읽는다).
 */
export function printStamp(at: Date): string {
  const date = `${at.getFullYear()}-${pad2(at.getMonth() + 1)}-${pad2(at.getDate())}`;
  const time = `${pad2(at.getHours())}:${pad2(at.getMinutes())}`;
  return `${date} ${time}`;
}
