-- 왜 값을 버리지 않고 폭을 넓히나:
--   "얼마부터 오류인가"를 지금 추측으로 정하고 싶지 않다. 원본을 그대로 담아 두면
--   나중에 화면·분석에서 신뢰등급으로 다룰 수 있고, 되돌릴 수도 있다. 반대로
--   적재 때 잘라 버리면 원본이 무엇이었는지 DB만 봐서는 알 수 없다.
--   ⚠️ 대신 **집계에 쓸 때 반드시 걸러야 한다** — 79,095% 하나가 평균을 통째로 오염시킨다.
--
-- 실행법: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run. (몇 초)
